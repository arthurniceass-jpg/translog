ALTER TABLE veiculos ADD COLUMN quilometragem BIGINT CHECK (quilometragem >= 0);

CREATE TABLE manutencoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    veiculo_id BIGINT NOT NULL REFERENCES veiculos(id),
    descricao VARCHAR(160) NOT NULL,
    prazo DATE,
    limite_km BIGINT CHECK (limite_km >= 0),
    status VARCHAR(24) NOT NULL CHECK (status IN ('AGENDADA', 'EM_EXECUCAO', 'CONCLUIDA')),
    concluida_em DATE,
    custo DECIMAL(12,2) CHECK (custo >= 0),
    CHECK (prazo IS NOT NULL OR limite_km IS NOT NULL),
    CHECK ((status = 'CONCLUIDA') = (concluida_em IS NOT NULL))
);
CREATE INDEX idx_manutencoes_veiculo ON manutencoes(veiculo_id);

CREATE TABLE viagens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    veiculo_id BIGINT NOT NULL REFERENCES veiculos(id),
    motorista_id BIGINT NOT NULL REFERENCES motoristas(id),
    origem VARCHAR(120) NOT NULL,
    destino VARCHAR(120) NOT NULL,
    partida TIMESTAMP NOT NULL,
    chegada_prevista TIMESTAMP NOT NULL,
    status VARCHAR(24) NOT NULL CHECK (status IN ('PROGRAMADA', 'EM_ANDAMENTO', 'CONCLUIDA', 'CANCELADA')),
    chegada_real TIMESTAMP,
    km_percorridos DECIMAL(10,2) CHECK (km_percorridos > 0),
    CHECK (chegada_prevista > partida),
    CHECK (chegada_real IS NULL OR chegada_real >= partida),
    CHECK ((status = 'CONCLUIDA' AND chegada_real IS NOT NULL AND km_percorridos IS NOT NULL)
        OR (status <> 'CONCLUIDA' AND chegada_real IS NULL AND km_percorridos IS NULL))
);
CREATE INDEX idx_viagens_veiculo_periodo ON viagens(veiculo_id, partida, chegada_prevista);
CREATE INDEX idx_viagens_motorista_periodo ON viagens(motorista_id, partida, chegada_prevista);

CREATE TABLE abastecimentos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    veiculo_id BIGINT NOT NULL REFERENCES veiculos(id),
    data DATE NOT NULL,
    litros DECIMAL(10,2) NOT NULL CHECK (litros > 0),
    valor DECIMAL(12,2) NOT NULL CHECK (valor > 0)
);
CREATE INDEX idx_abastecimentos_veiculo_data ON abastecimentos(veiculo_id, data);

CREATE TABLE documentos_frota (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    veiculo_id BIGINT UNIQUE REFERENCES veiculos(id),
    motorista_id BIGINT UNIQUE REFERENCES motoristas(id),
    validade DATE NOT NULL,
    CHECK ((veiculo_id IS NOT NULL AND motorista_id IS NULL) OR (veiculo_id IS NULL AND motorista_id IS NOT NULL))
);

CREATE TABLE ocorrencia_acompanhamento (
    ocorrencia_id BIGINT PRIMARY KEY REFERENCES ocorrencias(id) ON DELETE CASCADE,
    responsavel_id BIGINT REFERENCES usuarios(id),
    prazo DATE,
    prioridade VARCHAR(12) NOT NULL CHECK (prioridade IN ('BAIXA', 'NORMAL', 'ALTA', 'URGENTE'))
);

CREATE TABLE ocorrencia_status_historico (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ocorrencia_id BIGINT NOT NULL REFERENCES ocorrencias(id) ON DELETE CASCADE,
    usuario_id BIGINT REFERENCES usuarios(id),
    anterior VARCHAR(20),
    status VARCHAR(20) NOT NULL,
    registrado_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_ocorrencia_historico ON ocorrencia_status_historico(ocorrencia_id, id);

CREATE TABLE ocorrencia_anexos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ocorrencia_id BIGINT NOT NULL REFERENCES ocorrencias(id) ON DELETE CASCADE,
    nome VARCHAR(150) NOT NULL,
    tipo VARCHAR(32) NOT NULL,
    tamanho INTEGER NOT NULL CHECK (tamanho > 0 AND tamanho <= 5242880),
    conteudo BYTEA NOT NULL,
    enviado_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_ocorrencia_anexos ON ocorrencia_anexos(ocorrencia_id, id);
