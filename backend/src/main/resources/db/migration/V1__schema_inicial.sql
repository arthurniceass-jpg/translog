-- Schema inicial do TransLog (compatível com PostgreSQL e H2 em modo PostgreSQL)
-- Os valores de status/tipo guardam o NOME do enum Java (ex.: EM_USO).

CREATE TABLE usuarios (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome       VARCHAR(120) NOT NULL,
    email      VARCHAR(160) NOT NULL,
    senha_hash VARCHAR(100) NOT NULL,
    criado_em  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_usuarios_email UNIQUE (email)
);

CREATE TABLE veiculos (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    placa  VARCHAR(7)   NOT NULL,
    marca  VARCHAR(60)  NOT NULL,
    modelo VARCHAR(60)  NOT NULL,
    ano    INTEGER      NOT NULL,
    status VARCHAR(20)  NOT NULL,
    CONSTRAINT uq_veiculos_placa UNIQUE (placa)
);
CREATE INDEX idx_veiculos_status ON veiculos (status);

CREATE TABLE motoristas (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome     VARCHAR(120) NOT NULL,
    cpf      VARCHAR(11)  NOT NULL,
    cnh      VARCHAR(11)  NOT NULL,
    telefone VARCHAR(11)  NOT NULL,
    status   VARCHAR(20)  NOT NULL,
    CONSTRAINT uq_motoristas_cpf UNIQUE (cpf),
    CONSTRAINT uq_motoristas_cnh UNIQUE (cnh)
);
CREATE INDEX idx_motoristas_status ON motoristas (status);

-- Categorias da CNH (A..E): uma linha por categoria do motorista
CREATE TABLE motorista_categorias (
    motorista_id BIGINT  NOT NULL,
    categoria    VARCHAR(1) NOT NULL,
    PRIMARY KEY (motorista_id, categoria),
    CONSTRAINT fk_motorista_categorias_motorista FOREIGN KEY (motorista_id) REFERENCES motoristas (id) ON DELETE CASCADE
);

CREATE TABLE ocorrencias (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo       VARCHAR(160) NOT NULL,
    tipo         VARCHAR(20)  NOT NULL,
    descricao    VARCHAR(2000) NOT NULL,
    data         DATE         NOT NULL,
    status       VARCHAR(20)  NOT NULL,
    veiculo_id   BIGINT       NOT NULL,
    motorista_id BIGINT,
    CONSTRAINT fk_ocorrencias_veiculo   FOREIGN KEY (veiculo_id)   REFERENCES veiculos (id),
    CONSTRAINT fk_ocorrencias_motorista FOREIGN KEY (motorista_id) REFERENCES motoristas (id)
);
CREATE INDEX idx_ocorrencias_status   ON ocorrencias (status);
CREATE INDEX idx_ocorrencias_tipo     ON ocorrencias (tipo);
CREATE INDEX idx_ocorrencias_data     ON ocorrencias (data);
CREATE INDEX idx_ocorrencias_veiculo  ON ocorrencias (veiculo_id);
CREATE INDEX idx_ocorrencias_motorista ON ocorrencias (motorista_id);
